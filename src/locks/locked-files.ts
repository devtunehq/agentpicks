/**
 * ABOUTME: The committed form of a generated project: its files exactly as the generator left
 * them (lockfiles included) plus any lock kept outside the project, how a sandbox capture of
 * one is parsed, how it is packed for upload and how it is written out as a TypeScript module.
 */

export type LockedEntry =
  | { path: string; kind: 'file'; executable: boolean; text: string }
  | { path: string; kind: 'file'; executable: boolean; base64: string }
  | { path: string; kind: 'dir' }
  | { path: string; kind: 'link'; target: string };

export interface LockedStarter {
  /** The project as the generator produced it, without what the frozen install recreates. */
  files: LockedEntry[];
  /** Locks the generator does not produce, kept out of the project (Python's hashed requirements). */
  locks: LockedEntry[];
}

/** The file's bytes. */
export function entryBytes(
  entry: Extract<LockedEntry, { kind: 'file' }>,
): Buffer {
  return 'text' in entry
    ? Buffer.from(entry.text, 'utf8')
    : Buffer.from(entry.base64, 'base64');
}

/**
 * Packs entries for `unpack` in make-env.sh and setup.sh: one line per entry,
 * `<644|755|dir|link>\t<path>\t<base64 of the content or link target>`.
 */
export function packEntries(entries: LockedEntry[]): string {
  return entries
    .map((e) => {
      if (e.kind === 'dir') return `dir\t${e.path}\t`;
      if (e.kind === 'link')
        return `link\t${e.path}\t${Buffer.from(e.target).toString('base64')}`;
      return `${e.executable ? '755' : '644'}\t${e.path}\t${entryBytes(e).toString('base64')}`;
    })
    .map((line) => `${line}\n`)
    .join('');
}

/** Bytes that survive a round trip through UTF-8 and need no escaping beyond a template literal's. */
function asText(bytes: Buffer): string | null {
  const text = bytes.toString('utf8');
  if (!Buffer.from(text, 'utf8').equals(bytes)) return null;
  // Control characters other than tab, newline and carriage return stay base64.
  for (const char of text) {
    const code = char.charCodeAt(0);
    if ((code < 0x20 && !'\t\n\r'.includes(char)) || code === 0x7f) return null;
  }
  return text;
}

/** Parses the packed lines a sandbox capture writes, the inverse of `packEntries`. */
export function parsePackedEntries(packed: string): LockedEntry[] {
  return packed
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const [mode, path, data = ''] = line.split('\t');
      if (!mode || !path) throw new Error(`malformed locked entry: ${line}`);
      if (mode === 'dir') return { path, kind: 'dir' };
      const bytes = Buffer.from(data, 'base64');
      if (mode === 'link')
        return { path, kind: 'link', target: bytes.toString('utf8') };
      if (mode !== '644' && mode !== '755')
        throw new Error(`unknown mode ${mode} for ${path}`);
      const executable = mode === '755';
      const text = asText(bytes);
      return text === null
        ? { path, kind: 'file', executable, base64: data }
        : { path, kind: 'file', executable, text };
    });
}

/** A template literal whose value is exactly `text`. */
function templateLiteral(text: string): string {
  return `\`${text
    .replaceAll('\\', '\\\\')
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${')
    .replaceAll('\r', '\\r')}\``;
}

function renderEntry(entry: LockedEntry): string {
  const path = JSON.stringify(entry.path);
  if (entry.kind === 'dir') return `  { path: ${path}, kind: 'dir' },`;
  if (entry.kind === 'link')
    return `  { path: ${path}, kind: 'link', target: ${JSON.stringify(entry.target)} },`;
  const body =
    'text' in entry
      ? `text: ${templateLiteral(entry.text)}`
      : `base64: ${JSON.stringify(entry.base64)}`;
  return `  {\n    path: ${path},\n    kind: 'file',\n    executable: ${entry.executable},\n    ${body},\n  },`;
}

/**
 * The generated module for one starter: `export const LOCKED: LockedStarter`. Regenerated
 * by `pnpm --filter web agent-picks:lock-environments`; never edited by hand.
 */
export function renderLockedStarterModule(
  key: string,
  starter: LockedStarter,
): string {
  const list = (entries: LockedEntry[]) =>
    entries.length === 0
      ? '[]'
      : `[\n${entries.map(renderEntry).join('\n')}\n]`;
  return `/**
 * ABOUTME: Generated by \`pnpm --filter web agent-picks:lock-environments\`; do not edit. The
 * committed ${key} starter: the generator's output with its lockfiles, laid down and
 * installed frozen by every setup.
 */
import type { LockedStarter } from './locked-files';

export const LOCKED: LockedStarter = {
  files: ${list(starter.files)},
  locks: ${list(starter.locks)},
};
`;
}

/** A starter key as a module identifier: `nextjs-supabase` → `nextjsSupabase`. */
function identifier(key: string): string {
  return key.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** The generated `locks/index.ts`: every committed starter by key, plus the agent tools. */
export function renderLockedIndexModule(keys: string[]): string {
  const sorted = [...keys].sort();
  return `/**
 * ABOUTME: Generated by \`pnpm --filter web agent-picks:lock-environments\`; do not edit. Every
 * committed starter by key, and the agent tools under \`agent-tools\`.
 */
${sorted.map((k) => `import { LOCKED as ${identifier(k)} } from './${k}';`).join('\n')}
import type { LockedStarter } from './locked-files';

export const LOCKED_STARTERS: Record<string, LockedStarter> = {
${sorted.map((k) => `  ${/^[a-z]+$/.test(k) ? k : `'${k}'`}: ${identifier(k)},`).join('\n')}
};
`;
}
