/**
 * ABOUTME: The format of a self-run bundle, the directory `agentpicks run` writes for one run and
 * DevTune ingests: `manifest.json` (the run's context), `redactions.json` (what redaction removed)
 * and `artifacts/<name>` for each artifact the run captured, already redacted. The schemas parse
 * both JSON files; the server imports them to read an upload.
 */
import { z } from 'zod';

import { PROMPT_INTENTS } from '../catalogue/prompt-intents';
import { AGENT_KINDS } from '../run/agent-kind';
import { RUN_ARTIFACTS } from '../run/sandbox-run';

/**
 * Whether a remote address holds only its host and path: no `@` before the host (userinfo), no
 * query or fragment, and no `transport::` helper prefix.
 */
export function isHostAndPath(url: string): boolean {
  if (/[?#]/.test(url) || url.includes('::')) return false;
  const authority = /^[A-Za-z][A-Za-z0-9+.-]*:\/\/([^/]*)/.exec(url)?.[1];
  return !(authority ?? url.split(':')[0]!).includes('@');
}

/** The bundle format's version; a reader refuses one it does not know. */
export const BUNDLE_VERSION = 1;

/** Where each part of a bundle lives, relative to its directory. */
export const BUNDLE_PATHS = {
  manifest: 'manifest.json',
  redactions: 'redactions.json',
  artifacts: 'artifacts',
} as const;

const artifactName = z.enum(RUN_ARTIFACTS);
const sha256 = z.string().regex(/^[0-9a-f]{64}$/);

/** One captured artifact as written to `artifacts/<name>`: its size and SHA-256 after redaction. */
export const bundleArtifactSchema = z.object({
  name: artifactName,
  bytes: z.number().int().nonnegative(),
  sha256,
  /** Byte counts after redaction, before and after whole-line trimming for upload. Older readers ignore this field. */
  truncation: z
    .object({
      originalBytes: z.number().int().nonnegative(),
      keptBytes: z.number().int().nonnegative(),
    })
    .optional(),
});

/**
 * A run's context (spec 46 §3.7), as the customer's machine reports it; nothing in it is
 * verified, so it is never published. It names the starter (`stack`) or the customer's
 * repository (`repository`) the run tested, never both.
 */
export const bundleManifestSchema = z
  .object({
    bundleVersion: z.literal(BUNDLE_VERSION),
    /** Generated by the runner for this run. */
    runId: z.uuid(),
    runner: z.object({
      name: z.literal('@devtune/agentpicks'),
      version: z.string().min(1),
    }),
    agent: z.object({
      kind: z.enum(AGENT_KINDS),
      /** The version installed on the host, which the sandbox installed too. */
      version: z.string().min(1),
      /** The model the agent was asked for; `default` is the agent's own default. */
      model: z.string().min(1),
    }),
    /** `process.platform` and `process.arch` of the machine that ran it. */
    host: z.object({ os: z.string().min(1), arch: z.string().min(1) }),
    sandbox: z.object({
      provider: z.literal('docker'),
      /** The id (`sha256:…`) of the image the container ran. */
      imageDigest: z.string().regex(/^sha256:[0-9a-f]{64}$/),
      /** The address the container reached the internet from; null when it could not be read. */
      egressIp: z.union([z.ipv4(), z.ipv6()]).nullable(),
    }),
    /** The committed starter the project was laid down from (`--stack`). */
    stack: z
      .object({
        slug: z.string().min(1),
        starter: z.string().min(1),
        /** SHA-256 of the starter's committed files and lockfiles, as uploaded to the sandbox. */
        lockDigest: sha256,
      })
      .optional(),
    /** The customer's repository the project was copied from (`--repo`), at the commit tested. */
    repository: z
      .object({
        /** The `origin` remote, or the first remote, as host and path; null with none or one not read with confidence. */
        remoteUrl: z
          .string()
          .min(1)
          .refine(isHostAndPath, {
            message: 'a remote URL is its host and path alone',
          })
          .nullable(),
        /** The full commit id, which is also the baseline the diff is taken against. */
        commit: z.string().regex(/^[0-9a-f]{40}([0-9a-f]{24})?$/),
      })
      .optional(),
    request: z.object({
      category: z.string().min(1),
      intent: z.enum(PROMPT_INTENTS),
      /** The exact prompt the agent received. */
      prompt: z.string().min(1),
    }),
    startedAt: z.iso.datetime({ offset: true }),
    finishedAt: z.iso.datetime({ offset: true }),
    artifacts: z.array(bundleArtifactSchema),
  })
  .refine((m) => (m.stack === undefined) !== (m.repository === undefined), {
    message: 'a manifest names a stack or a repository, not both',
  });

/** What redaction removed before the bundle was written: masked spans, per artifact. */
export const redactionSummarySchema = z.object({
  bundleVersion: z.literal(BUNDLE_VERSION),
  total: z.number().int().nonnegative(),
  byArtifact: z.partialRecord(artifactName, z.number().int().nonnegative()),
});

export type BundleArtifact = z.infer<typeof bundleArtifactSchema>;
export type BundleManifest = z.infer<typeof bundleManifestSchema>;
export type RedactionSummary = z.infer<typeof redactionSummarySchema>;
